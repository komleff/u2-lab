// Матрица тепловых пределов: ярус × класс × поколение. Civilian G1 — опора (предложение ГД, ТЗ §7),
// классы — конструктивные сдвиги по ярусам, поколения — закон U2 p(G) = 1 − 0,93^G с малыми асимптотами.
const p = (G) => 1 - 0.93 ** G;
const X = (x0, xinf, G, Ganchor) => x0 + (xinf - x0) * Math.max(0, p(G) - p(Ganchor)) / (1 - p(Ganchor)); // рост от опорного поколения класса
// Опора Civilian G1: [crit_low, work_low, work_high, crit_high]
const base = {
  "Точные: лазер, сенсоры": [220, 250, 500, 550],
  "Точные: солнечная панель": [150, 200, 500, 550],
  "Общие: электродвигатель": [210, 240, 530, 590],
  "Общие: аккумулятор": [220, 250, 520, 580],
  "Прочные: H₂-генератор": [240, 270, 540, 600],
  "Прочные: дизель-генератор": [200, 230, 560, 620],
  "Прочные: водородный двигатель": [190, 220, 560, 620],
  "Прочные: дизельный двигатель": [200, 230, 580, 640],
  "Прочные: баки": [150, 200, 580, 640],
  "Терморегуляция: насосы, H₂-охладитель, компрессор": [200, 230, 580, 630],
  "Печи": [150, 180, 500, 550],
  "Корпус": [150, 180, 650, 750],
};
// Сдвиги класса [Δcrit_low, Δwork_low, Δwork_high(точные/прочие), Δcrit_high(точные/прочие)], опорное поколение
const classes = {
  Civilian: { d: [0, 0, [0, 0], [0, 0]], G: 1, why: "опора" },
  Industrial: { d: [0, 0, [20, 20], [20, 20]], G: 2, why: "массивнее, запас на долгую работу" },
  Sport: { d: [0, 0, [30, 30], [10, 10]], G: 3, why: "лёгкие материалы, работа на грани: коридор снижения уже" },
  Military: { d: [-20, -20, [40, 60], [60, 80]], G: 4, why: "жаростойкие материалы; точные приборы выигрывают меньше" },
  Stealth: { d: [-30, -30, [-40, -40], [40, 40]], G: 5, why: "рассчитан работать холодным; длинный коридор снижения" },
};
// Асимптоты поколений (предложение ГД, намеренно малые): рабочие ±20 K, критические +60 / −40 K
const ASY = { crit_low: -40, work_low: -20, work_high: 20, crit_high: 60 };
const Gs = [null, 3, 5, 10];
for (const [cls, c] of Object.entries(classes)) {
  console.log(`\n== ${cls} (опорное поколение G${c.G}: ${c.why}) — крит.холод / раб.холод / раб.жар / крит.жар, K`);
  for (const [tier, b] of Object.entries(base)) {
    const precise = tier.startsWith("Точные");
    const g0 = [b[0] + c.d[0], b[1] + c.d[1], b[2] + c.d[2][precise ? 0 : 1], b[3] + c.d[3][precise ? 0 : 1]];
    const cells = Gs.map((G) => {
      const Gx = G ?? c.G;
      const v = [X(g0[0], g0[0] + ASY.crit_low, Gx, c.G), X(g0[1], g0[1] + ASY.work_low, Gx, c.G), X(g0[2], g0[2] + ASY.work_high, Gx, c.G), X(g0[3], g0[3] + ASY.crit_high, Gx, c.G)];
      return `G${Gx}: ${v.map((x) => x.toFixed(0)).join("/")}`;
    });
    console.log(`  ${tier.padEnd(48)} ${cells.join("   ")}`);
  }
}
